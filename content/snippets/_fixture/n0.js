/**
 * Extrait de test, référencé par la fiche valide des fixtures de schéma.
 *
 * La docstring d'en-tête prend la forme d'un bloc de commentaire, comme dans
 * les vrais extraits : c'est cette forme que la traduction remplace.
 */
export function normalise(texte) {
  return texte.trim().toLowerCase();
}
